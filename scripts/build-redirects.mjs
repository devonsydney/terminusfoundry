// Generate the redirect stubs for the two old Ghost hosts into redirects/sec/ and redirects/ev/.
// One meta-refresh page per old URL, each folder with its own CNAME and .nojekyll, ready to become
// the content of two small GitHub Pages repositories (plan of 2026-10-24). Run: npm run redirects
import fs from "node:fs";
import path from "node:path";

const site = JSON.parse(fs.readFileSync("src/_data/site.json", "utf8"));
const guides = JSON.parse(fs.readFileSync("src/_data/guides.json", "utf8"));

// Old URLs that were not in the Ghost export but are linked from post bodies (ev) or were served by nginx (sec).
const extras = {
  security: { "/static/securityscorecard_1.0.1.pdf/": `${site.url}/static/securityscorecard_1.0.1.pdf` },
  ev: { "/future-potential/": "future/", "/cool-capabilities/": "capabilities/" },
};

const slugsIn = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith(".html")).map((f) => f.replace(/\.html$/, ""));

function stub(to) {
  return [
    "<!DOCTYPE html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    "<title>Moved</title>",
    `<meta http-equiv="refresh" content="0; url=${to}">`,
    `<link rel="canonical" href="${to}">`,
    '<meta name="robots" content="noindex">',
    "</head>",
    "<body>",
    `<p>This page has moved to <a href="${to}">${to}</a>.</p>`,
    "</body>",
    "</html>",
    "",
  ].join("\n");
}

let total = 0;
for (const g of Object.values(guides)) {
  const base = `${site.url}/guides/${g.slug}/`;
  const outDir = path.join("redirects", g.source);
  fs.rmSync(outDir, { recursive: true, force: true });
  const map = new Map();
  const add = (oldPath, target) => map.set(oldPath, target.startsWith("http") ? target : base + target);
  add("/", "");
  add("/posts/", "");
  add("/rss/", "rss.xml");
  add("/posts/rss/", "rss.xml");
  add(`/author/${g.author.slug}/`, `author/${g.author.slug}/`);
  for (const t of g.tags) add(`/tag/${t.slug}/`, `tag/${t.slug}/`);
  for (const slug of slugsIn(`src/content/${g.source}/posts`)) add(`/${slug}/`, `${slug}/`);
  // Dropped pages: lastpass and contribute go to the guide index; tf (the old Terminus Foundry page) goes to the company home page.
  const pageTarget = (slug) => (["home", "lastpass", "contribute"].includes(slug) ? "" : slug === "tf" ? `${site.url}/` : `${slug}/`);
  for (const slug of slugsIn(`src/content/${g.source}/pages`)) add(`/${slug}/`, pageTarget(slug));
  for (const [oldPath, target] of Object.entries(extras[g.slug] || {})) add(oldPath, target);

  for (const [oldPath, target] of map) {
    const file = path.join(outDir, oldPath, "index.html");
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, stub(target));
    total += 1;
  }
  fs.writeFileSync(path.join(outDir, "404.html"), stub(base));
  fs.writeFileSync(path.join(outDir, "CNAME"), `${g.old_host}\n`);
  fs.writeFileSync(path.join(outDir, ".nojekyll"), "");
  fs.writeFileSync(path.join(outDir, "README.md"), [
    `# Redirects for ${g.old_host}`,
    "",
    `Generated by scripts/build-redirects.mjs in devonsydney/terminusfoundry; do not edit by hand. ${map.size} stubs, one per old URL, each a meta refresh to its new address under ${base}`,
    "",
    `Publish this folder as the root of a GitHub Pages repository with the custom domain ${g.old_host}.`,
    "",
  ].join("\n"));
  console.log(`${g.old_host}: ${map.size} stubs in ${outDir}/`);
}
console.log(`${total} redirect stubs written`);
